// Bundle src/ (CommonJS, relative requires only) into one Nuvio scraper file per target:
//   providers/arabhub.js (src/index.js) and providers/torbox.js (src/torbox/index.js)
//   node scripts/build.js
// Nuvio loads a single file per scraper, so every module is wrapped in a tiny require() registry.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const pkg = require(path.join(ROOT, "package.json"));
const manifest = require(path.join(ROOT, "manifest.json"));
const versionOf = (id) => (manifest.scrapers.find((s) => s.id === id) || {}).version || (pkg[id] && pkg[id].version) || pkg.version;

const TARGETS = [
  { id: "arabhub", entry: "src/index.js", out: "providers/arabhub.js", about: "Arab Hub - Nuvio local scraper aggregating Arabic movie/TV sources." },
  { id: "torbox", entry: "src/torbox/index.js", out: "providers/torbox.js", about: "TorBox - Nuvio local scraper for files in your TorBox library (Arabic + English titles)." },
];

let modules = [];
let ids = new Map();

function add(file) {
  if (ids.has(file)) return ids.get(file);
  const id = modules.length;
  ids.set(file, id);
  modules.push(null);
  let code = fs.readFileSync(file, "utf8");
  code = code.replace(/require\((["'])(\.{1,2}\/[^"']+)\1\)/g, (_, q, rel) => {
    let target = path.resolve(path.dirname(file), rel);
    if (!/\.js$/.test(target)) target += ".js";
    if (!fs.existsSync(target)) throw new Error(`${path.relative(ROOT, file)}: cannot resolve ${rel}`);
    return `__req(${add(target)})`;
  });
  if (/require\((["'])[^.]/.test(code)) throw new Error(`${path.relative(ROOT, file)}: bare require() is not available inside Nuvio`);
  modules[id] = { file: path.relative(ROOT, file).replace(/\\/g, "/"), code };
  return id;
}

function build(t) {
modules = [];
ids = new Map();
add(path.join(ROOT, t.entry));
const OUT = path.join(ROOT, t.out);

const banner = `// ${t.about.split(" - ")[0]} v${versionOf(t.id)} - ${t.about.split(" - ").slice(1).join(" - ")}
// GENERATED by scripts/build.js from src/ - edit the sources there, then run \`npm run build\`.
// Built ${new Date().toISOString()}
`;

const body = modules.map((m, i) => `/* ${i}: ${m.file} */\nfunction (module, exports, __req) {\n${m.code}\n}`).join(",\n");

const out = `${banner}
var __mods = [
${body}
];
var __cache = {};
function __req(i) {
  if (__cache[i]) return __cache[i].exports;
  var m = (__cache[i] = { exports: {} });
  __mods[i](m, m.exports, __req);
  return m.exports;
}
var __main = __req(0);
function getStreams(tmdbId, mediaType, season, episode) {
  return __main.getStreams(tmdbId, mediaType, season, episode);
}
var onSettings = __main.onSettings;
module.exports = onSettings ? { getStreams: getStreams, onSettings: onSettings } : { getStreams: getStreams };
`;

// Nuvio runs providers on Hermes, which can't run async/await in dynamically loaded code: lower the
// bundle to ES2016 (async -> generators, object spread etc.), the same target Nuvio's own build uses.
const esbuild = require("esbuild");
const lowered = esbuild.transformSync(out, { target: "es2016", format: "cjs", legalComments: "inline" }).code;
if (/\basync\s+(?:function|\(|[A-Za-z_$][\w$]*\s*=>)|\bawait\s/.test(lowered.replace(/\/\/.*$/gm, ""))) {
  throw new Error("async/await survived transpilation");
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lowered);
console.log(`built ${path.relative(ROOT, OUT)}: ${modules.length} modules, ${(lowered.length / 1024).toFixed(1)} KB (es2016)`);
}

TARGETS.forEach(build);
