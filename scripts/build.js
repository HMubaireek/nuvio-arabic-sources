// Bundle src/ (CommonJS, relative requires only) into one Nuvio scraper file: providers/arabhub.js
//   node scripts/build.js
// Nuvio loads a single file per scraper, so every module is wrapped in a tiny require() registry.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const ENTRY = path.join(ROOT, "src", "index.js");
const OUT = path.join(ROOT, "providers", "arabhub.js");
const pkg = require(path.join(ROOT, "package.json"));

const modules = [];
const ids = new Map();

function add(file) {
  if (ids.has(file)) return ids.get(file);
  const id = modules.length;
  ids.set(file, id);
  modules.push(null);
  let code = fs.readFileSync(file, "utf8");
  code = code.replace(/require\((["'])(\.{1,2}\/[^"']+)\1\)/g, (_, q, rel) => {
    let target = path.resolve(path.dirname(file), rel);
    if (!/\.js$/.test(target)) target += ".js";
    if (!fs.existsSync(target)) throw new Error(`${path.relative(ROOT, file)}: cannot resolve ${rel}`);
    return `__req(${add(target)})`;
  });
  if (/require\((["'])[^.]/.test(code)) throw new Error(`${path.relative(ROOT, file)}: bare require() is not available inside Nuvio`);
  modules[id] = { file: path.relative(ROOT, file).replace(/\\/g, "/"), code };
  return id;
}

add(ENTRY);

const banner = `// Arab Hub v${pkg.version} - Nuvio local scraper aggregating Arabic movie/TV sources.
// GENERATED by scripts/build.js from src/ - edit the sources there, then run \`npm run build\`.
// Built ${new Date().toISOString()}
`;

const body = modules.map((m, i) => `/* ${i}: ${m.file} */\nfunction (module, exports, __req) {\n${m.code}\n}`).join(",\n");

const out = `${banner}
var __mods = [
${body}
];
var __cache = {};
function __req(i) {
  if (__cache[i]) return __cache[i].exports;
  var m = (__cache[i] = { exports: {} });
  __mods[i](m, m.exports, __req);
  return m.exports;
}
var __hub = __req(0);
function getStreams(tmdbId, mediaType, season, episode) {
  return __hub.getStreams(tmdbId, mediaType, season, episode);
}
module.exports = { getStreams: getStreams };
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`built ${path.relative(ROOT, OUT)}: ${modules.length} modules, ${(out.length / 1024).toFixed(1)} KB`);
